"""
Novel Candidate Discovery Script:
Screens unobserved gene-disease pairs and produces ranked candidate hypotheses
for further biological investigation.
"""

import argparse
from pathlib import Path
import sys
import pandas as pd
import torch

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from src.data import DataLoaderManager
from src.similarity import GraphNeighborhoodManager
from src.utils import set_global_seed
from src.models.transf_gda import TransGDA
from src.train import TransGDATrainer, get_optimal_device
from src.discovery import NovelCandidateDiscovery


def run_discovery_pipeline(epochs: int = 12, output_dir: str = "results", top_n: int = 25):
    set_global_seed(42)
    out_path = Path(output_dir)
    out_path.mkdir(parents=True, exist_ok=True)

    device = get_optimal_device()
    data_mgr = DataLoaderManager(data_dir=".")
    # Train on 90% of data to maximize coverage while retaining validation checkpointing
    split = data_mgr.create_edge_split(val_ratio=0.10, test_ratio=0.01, seed=42)

    print("Building dynamic leakage-free similarity graphs...")
    graph_mgr = GraphNeighborhoodManager(
        num_genes=data_mgr.meta.num_genes,
        num_diseases=data_mgr.meta.num_diseases,
        k_gene_neighbors=16,
        k_disease_neighbors=16,
    )
    graph_mgr.build_from_train_matrix(split.train_matrix_binary, metric="cosine")

    train_loader, val_loader, _ = data_mgr.build_torch_dataloaders(
        split, batch_size=256, shuffle_train=True
    )

    print(f"Training TransGDA model for discovery screening ({epochs} epochs)...")
    model = TransGDA(
        num_genes=data_mgr.meta.num_genes,
        num_diseases=data_mgr.meta.num_diseases,
        embed_dim=64,
        num_heads=4,
        ffn_dim=128,
        hidden_dim=128,
        dropout=0.1,
    )
    trainer = TransGDATrainer(
        model=model,
        graph_manager=graph_mgr,
        device=device,
        lr=1e-3,
        lambda_strength=1.0,
    )
    trainer.fit(train_loader, val_loader, epochs=epochs, patience=3, verbose=True)

    discovery_engine = NovelCandidateDiscovery(
        model=model,
        graph_manager=graph_mgr,
        data_manager=data_mgr,
        device=device,
    )

    # Focus screening on key disease families
    target_diseases = [
        "parkinson's disease",
        "breast cancer",
        "lymphoid leukemia",
        "alzheimer's disease",
        "rheumatoid arthritis",
        "colorectal cancer",
        "ovarian cancer",
        "prostate cancer",
        "lung cancer",
        "multiple sclerosis",
    ]

    # Filter to diseases existing in metadata
    valid_diseases = [d for d in target_diseases if d in data_mgr.meta.disease_to_idx]
    print(f"\nScreening unobserved pairs for {len(valid_diseases)} target clinical diseases...")

    df_candidates = discovery_engine.screen_unobserved_pairs(
        min_prob=0.75,
        batch_size=1024,
        target_diseases=valid_diseases,
    )

    print(f"Found {len(df_candidates):,} unobserved pairs with existence probability >= 0.75!")

    csv_path = out_path / "novel_candidates.csv"
    report_md = discovery_engine.generate_discovery_report(
        df_candidates, top_n=top_n, output_csv=csv_path
    )

    full_md_path = out_path / "novel_discoveries.md"
    with open(full_md_path, "w") as f:
        f.write("# TransGDA Novel Gene–Disease Candidates\n\n")
        f.write("The following unobserved gene–disease pairs were predicted with high confidence (existence probability $\ge 0.75$) and quantified association strength:\n\n")
        f.write(report_md)
        f.write("\n\n---\n*Candidate hypotheses generated by TransGDA for biological validation.*")

    print(f"\nTop novel candidates saved to:\n  - CSV: {csv_path}\n  - Report: {full_md_path}")


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--epochs", type=int, default=12)
    parser.add_argument("--output_dir", type=str, default="results")
    parser.add_argument("--top_n", type=int, default=25)
    args = parser.parse_args()
    run_discovery_pipeline(epochs=args.epochs, output_dir=args.output_dir, top_n=args.top_n)
